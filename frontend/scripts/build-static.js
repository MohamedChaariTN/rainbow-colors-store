const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const storeSource = path.join(root, "store");
const adminSource = path.join(root, "admin");
const output = path.join(root, "public");
const markerName = ".rainbow-colors-static-output";
const excludedRelativePaths = new Set([
  path.join("css", "rainbow-colors-store.zip")
]);

function fail(message) {
  console.error(`Static build stopped: ${message}`);
  process.exit(1);
}

function assertDirectory(dir, label) {
  if (!fs.existsSync(dir) || !fs.statSync(dir).isDirectory()) {
    fail(`required ${label} directory was not found: ${dir}`);
  }
}

function copyTree(source, destination, relative = "") {
  fs.mkdirSync(destination, { recursive: true });
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    const rel = path.join(relative, entry.name);
    if (excludedRelativePaths.has(rel)) {
      console.log(`Excluded from static output: ${path.relative(root, path.join(source, entry.name))}`);
      continue;
    }
    const from = path.join(source, entry.name);
    const to = path.join(destination, entry.name);
    if (entry.isSymbolicLink()) {
      fail(`symbolic links are not allowed in source content: ${from}`);
    }
    if (entry.isDirectory()) {
      copyTree(from, to, rel);
    } else if (entry.isFile()) {
      fs.copyFileSync(from, to);
    }
  }
}

assertDirectory(storeSource, "store");
assertDirectory(adminSource, "admin");

if (path.dirname(output) !== root || path.basename(output) !== "public") {
  fail("output path did not match the expected frontend/public directory");
}
if (fs.existsSync(output)) {
  const stat = fs.lstatSync(output);
  if (stat.isSymbolicLink() || !stat.isDirectory()) {
    fail("output exists but is not a normal directory");
  }
  const entries = fs.readdirSync(output);
  if (entries.length > 0 && !entries.includes(markerName)) {
    fail("refusing to replace a non-empty public directory without the Rainbow Colors build marker");
  }
  fs.rmSync(output, { recursive: true, force: true });
}

fs.mkdirSync(output, { recursive: true });
copyTree(storeSource, output);
copyTree(adminSource, path.join(output, "admin"));

const adminImages = path.join(adminSource, "images");
const outputAdminImages = path.join(output, "admin", "images");
if (!fs.existsSync(adminImages) && fs.existsSync(path.join(storeSource, "images"))) {
  copyTree(path.join(storeSource, "images"), outputAdminImages);
  console.log("Admin image mirror: store/images -> admin/images");
}

fs.writeFileSync(path.join(output, markerName), "Generated by scripts/build-static.js\n", "utf8");

let files = 0;
let bytes = 0;
function measure(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      measure(full);
    } else if (entry.isFile()) {
      files += 1;
      bytes += fs.statSync(full).size;
    }
  }
}
measure(output);

console.log("Static build completed.");
console.log(`  output: ${path.relative(root, output)}`);
console.log(`  files: ${files}`);
console.log(`  bytes: ${bytes}`);
console.log("  store: store");
console.log("  admin: admin");
